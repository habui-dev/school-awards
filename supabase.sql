alter table public.nominees enable row level security;
alter table public.votes enable row level security;
alter table public.site_settings enable row level security;

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.admins enable row level security;
drop policy if exists "Admins can view admin list" on public.admins;
create policy "Admins can view admin list" on public.admins for select to authenticated using (user_id=auth.uid());

-- Public can view nominee names/photo paths and voting status.
drop policy if exists "Anyone can view nominees" on public.nominees;
create policy "Anyone can view nominees" on public.nominees for select to anon, authenticated using (true);
drop policy if exists "Anyone can view voting status" on public.site_settings;
create policy "Anyone can view voting status" on public.site_settings for select to anon, authenticated using (true);

-- Public can submit votes without logging in. Deliberately allows repeat votes.
drop policy if exists "Anyone can vote" on public.votes;
create policy "Anyone can vote" on public.votes for insert to anon, authenticated with check (
 category in ('Miss Beauty','Miss Connection','Miss Friendship','Miss Humour','School Princess')
 and exists(select 1 from public.site_settings s where s.id=1 and s.voting_open=true)
);
-- The public results view reveals counts only, not vote timestamps or individual vote rows.
drop policy if exists "Admins can read raw votes" on public.votes;
create policy "Admins can read raw votes" on public.votes for select to authenticated using (
 exists(select 1 from public.admins a where a.user_id=auth.uid())
);

create table if not exists public.admins (
 user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.admins enable row level security;
drop policy if exists "Admins can view admin list" on public.admins;
create policy "Admins can view admin list" on public.admins for select to authenticated using (user_id=auth.uid());

drop policy if exists "Admins can update nominees" on public.nominees;
create policy "Admins can update nominees" on public.nominees for update to authenticated using (
 exists(select 1 from public.admins a where a.user_id=auth.uid())
) with check (exists(select 1 from public.admins a where a.user_id=auth.uid()));
drop policy if exists "Admins can update voting setting" on public.site_settings;
create policy "Admins can update voting setting" on public.site_settings for update to authenticated using (
 exists(select 1 from public.admins a where a.user_id=auth.uid())
) with check (exists(select 1 from public.admins a where a.user_id=auth.uid()));

create or replace view public.public_vote_results as
select v.category, v.nominee_id, count(*)::bigint as vote_count
from public.votes v
group by v.category,v.nominee_id;
grant select on public.nominees to anon, authenticated;
grant select, insert on public.votes to anon, authenticated;
grant select on public.site_settings to anon, authenticated;
grant update on public.site_settings to authenticated;
grant update (photo_path) on public.nominees to authenticated;
grant select on public.public_vote_results to anon, authenticated;
grant select on public.admins to authenticated;

-- Storage bucket for public nominee photos. Host/admin-only uploads.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('nominee-photos','nominee-photos',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=true,file_size_limit=5242880,allowed_mime_types=array['image/jpeg','image/png','image/webp'];
drop policy if exists "Anyone can view nominee photos" on storage.objects;
create policy "Anyone can view nominee photos" on storage.objects for select to anon, authenticated using (bucket_id='nominee-photos');
drop policy if exists "Admins can upload nominee photos" on storage.objects;
create policy "Admins can upload nominee photos" on storage.objects for insert to authenticated with check (
 bucket_id='nominee-photos' and exists(select 1 from public.admins a where a.user_id=auth.uid())
);
drop policy if exists "Admins can update nominee photos" on storage.objects;
create policy "Admins can update nominee photos" on storage.objects for update to authenticated using (
 bucket_id='nominee-photos' and exists(select 1 from public.admins a where a.user_id=auth.uid())
) with check (bucket_id='nominee-photos' and exists(select 1 from public.admins a where a.user_id=auth.uid()));
drop policy if exists "Admins can delete nominee photos" on storage.objects;
create policy "Admins can delete nominee photos" on storage.objects for delete to authenticated using (
 bucket_id='nominee-photos' and exists(select 1 from public.admins a where a.user_id=auth.uid())
);
