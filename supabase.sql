-- Run this whole file in Supabase Dashboard > SQL Editor after creating the project.
create extension if not exists pgcrypto;

create table if not exists public.nominees (
  id integer generated by default as identity primary key,
  name text not null unique,
  photo_path text,
  sort_order integer not null unique
);
create table if not exists public.votes (
  id bigint generated always as identity primary key,
  category text not null check (category in ('Miss Beauty','Miss Connection','Miss Friendship','Miss Humour','School Princess')),
  nominee_id integer not null references public.nominees(id),
  created_at timestamptz not null default now()
);
create table if not exists public.site_settings (
  id integer primary key check (id = 1),
  voting_open boolean not null default true
);
insert into public.site_settings(id,voting_open) values (1,true)
on conflict (id) do nothing;

